import pandas as pd
import numpy as np
# Создаем датафреймы с ценами на товары в двух магазинах
df1 = pd.DataFrame({
    'Товар': ['Шоколад', 'Молоко', 'Хлеб', 'Масло'],
    'Цена': [100, 50, 30, 150]
})
df2 = pd.DataFrame({
    'Товар': ['Шоколад', 'Молоко', 'Хлеб', 'Масло'],
    'Цена': [120, 60, 35, 140]
})
price = df1['Цена'] - df2['Цена']
df = pd.DataFrame(df1)
del df['Цена']
df['Разница'] = price
print(df)